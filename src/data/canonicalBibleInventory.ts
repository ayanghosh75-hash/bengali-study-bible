export function getCanonicalBook(id: string): CanonicalBook | undefined {
  return CANONICAL_BIBLE_INVENTORY.find((b) => b.id.toUpperCase() === id.toUpperCase());
}

export function getCanonicalBookByNumber(num: number): CanonicalBook | undefined {
  return CANONICAL_BIBLE_INVENTORY.find((b) => b.bookNumber === num);
}

export function getCanonicalBookByName(name: string): CanonicalBook | undefined {
  const clean = name.trim().toLowerCase();
  return CANONICAL_BIBLE_INVENTORY.find(
    (b) =>
      b.nameBn.toLowerCase() === clean ||
      b.nameEn.toLowerCase() === clean ||
      b.shortNameBn.toLowerCase() === clean ||
      b.abbreviation.toLowerCase() === clean ||
      b.id.toLowerCase() === clean
  );
}

export function getCanonicalStats() {
  const ot = CANONICAL_BIBLE_INVENTORY.filter((b) => b.testament === 'OT');
  const nt = CANONICAL_BIBLE_INVENTORY.filter((b) => b.testament === 'NT');
  return {
    totalBooks: CANONICAL_BIBLE_INVENTORY.length,
    otBooksCount: ot.length,
    ntBooksCount: nt.length,
    totalChapters: CANONICAL_BIBLE_INVENTORY.reduce((sum, b) => sum + b.chaptersCount, 0),
    otChaptersCount: ot.reduce((sum, b) => sum + b.chaptersCount, 0),
    ntChaptersCount: nt.reduce((sum, b) => sum + b.chaptersCount, 0),
    totalVerses: CANONICAL_BIBLE_INVENTORY.reduce((sum, b) => sum + b.verseCount, 0),
    otVersesCount: ot.reduce((sum, b) => sum + b.verseCount, 0),
    ntVersesCount: nt.reduce((sum, b) => sum + b.verseCount, 0),
  };
}
