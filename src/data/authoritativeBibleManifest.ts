/**
 * Find canonical book by name, alias, or abbreviation (Bengali or English).
 */
export function findBookByAliasOrAbbreviation(query: string): ManifestBook | undefined {
  if (!query) return undefined;
  const clean = query.trim().toLowerCase();
  
  // Direct id check
  const byId = AUTHORITATIVE_BIBLE_MANIFEST.find(b => b.id.toLowerCase() === clean);
  if (byId) return byId;

  // Name check
  const byName = AUTHORITATIVE_BIBLE_MANIFEST.find(
    b => b.nameEn.toLowerCase() === clean || b.nameBn.trim() === query.trim()
  );
  if (byName) return byName;

  // Alias lookup
  const mappedId = CANONICAL_BOOK_ALIASES_MAP[query.trim()] || CANONICAL_BOOK_ALIASES_MAP[clean];
  if (mappedId) {
    return getManifestBook(mappedId);
  }

  // Partial match in nameBn or nameEn
  return AUTHORITATIVE_BIBLE_MANIFEST.find(
    b => b.nameBn.includes(query.trim()) || b.nameEn.toLowerCase().includes(clean)
  );
}

/**
 * Retrieve verified SHA-256 checksum for a canonical book from storage or metadata.
 */
export function getBookChecksum(bookId: string): string | undefined {
  const book = getManifestBook(bookId);
  return book?.checksumSha256;
}

